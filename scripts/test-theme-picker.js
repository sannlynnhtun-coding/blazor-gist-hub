// Browser regression: run checkThemePicker() in a loaded GistHub page.
async function checkThemePicker() {
    const root = document.querySelector('.neo-theme-picker');
    const panel = root.querySelector('[popover]');
    const search = panel.querySelector('input');
    const option = id => panel.querySelector(`[data-theme-option="${id}"]`);
    const check = (ok, message) => { if (!ok) throw new Error(message); };
    const settle = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
    const original = root.dataset.savedTheme;
    const previewTheme = window.getGistHubThemes().find(theme => theme.id !== original).id;
    const nordTheme = window.getGistHubThemes().find(theme => theme.name === 'Nord').id;
    const saved = localStorage.getItem('theme');
    panel.showPopover();
    await settle();
    option(previewTheme).dispatchEvent(new PointerEvent('pointerover', { bubbles: true }));
    check(document.documentElement.dataset.theme === previewTheme, 'Hover must preview immediately');
    check(localStorage.getItem('theme') === saved, 'Preview must not overwrite the saved choice');
    search.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
    await settle();
    check(!panel.matches(':popover-open') && document.documentElement.dataset.theme === original, 'Escape must close and restore');
    panel.showPopover();
    await settle();
    search.value = 'nord';
    search.dispatchEvent(new Event('input', { bubbles: true }));
    check([...panel.querySelectorAll('[data-theme-option]:not([hidden])')].every(el => el.dataset.themeName.toLowerCase().includes('nord')), 'Search must filter options');
    search.focus();
    search.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true }));
    check(document.activeElement.dataset.themeOption?.includes('nord'), 'Arrow keys must focus and preview filtered options');
    check(localStorage.getItem('theme') === saved, 'Keyboard preview must not save');
    option(nordTheme).click();
    for (let frame = 0; frame < 30 && (root.dataset.savedTheme !== nordTheme || panel.matches(':popover-open') || document.documentElement.dataset.theme !== nordTheme); frame++) await settle();
    check(root.dataset.savedTheme === nordTheme && localStorage.getItem('theme') === nordTheme, 'Selection must save');
    await settle();
    check(!panel.matches(':popover-open') && document.documentElement.dataset.theme === nordTheme, 'Closing after selection must retain the chosen theme');
    panel.showPopover();
    await settle();
    search.value = 'no-matching-theme-123';
    search.dispatchEvent(new Event('input', { bubbles: true }));
    check(!panel.querySelector('.neo-theme-panel__empty').hidden, 'No matches must show an empty state');
    search.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true }));
    search.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
    await settle();
    check(document.documentElement.dataset.theme === nordTheme, 'Cancel must restore the last committed choice');
    panel.showPopover();
    await settle();
    option(original).click();
    await settle();
    return 'PASS: hover and keyboard previews, filtering, empty results, Escape rollback, save and close behavior.';
}
